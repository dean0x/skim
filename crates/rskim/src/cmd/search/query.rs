/// Format query results as human-readable text to `w`.
///
/// Format per result:
/// ```text
/// src/auth/middleware.rs:42  [function_signature]  score: 12.34
///   41│ /// Validates JWT token
///   42│ pub fn authenticate(req: &Request) -> Result<Claims> {
///   43│     let header = req.header("Authorization")
/// ```
#[cfg(test)]
pub(super) fn format_text_output(
    output: &QueryOutput,
    w: &mut impl std::io::Write,
) -> anyhow::Result<()> {
    if output.results.is_empty() {
        writeln!(w, "no results for {:?}", output.query)?;
        return Ok(());
    }

    for r in &output.results {
        let line_info = r.line_number.map(|ln| format!(":{ln}")).unwrap_or_default();
        let stale_tag = if r.stale { "  [stale]" } else { "" };

        writeln!(
            w,
            "{}{}  [{}]  score: {:.2}{}",
            r.path, line_info, r.field, r.score, stale_tag
        )?;

        if let Some(ctx) = &r.snippet {
            for line in &ctx.lines {
                let marker = if line.is_match { ">" } else { " " };
                writeln!(w, "  {}  {:>4}│ {}", marker, line.line_number, line.content)?;
            }
        }
        writeln!(w)?;
    }

    // AD-412-4: Echo the effective query in the human summary so a mangled query
    // can never masquerade as a successful search.  {:?} matches the empty-branch
    // quoting convention (`no results for {:?}`) for uniform escaping.
    // JSON output already carries `query` and is unaffected by this change.
    writeln!(
        w,
        "{} result(s) for {:?} in {}ms",
        output.total, output.query, output.duration_ms
    )?;

    Ok(())
}

/// Format query results as a JSON object to `w`.
#[cfg(test)]
pub(super) fn format_json_output(
    output: &QueryOutput,
    w: &mut impl std::io::Write,
) -> anyhow::Result<()> {
    let json = serde_json::to_string_pretty(output)?;
    writeln!(w, "{json}")?;
    Ok(())
}

/// Format the bounded-page stderr notice emitted whenever `has_more=true`.
///
/// Fires when the verified candidate pool exceeds the requested page, so a
/// reader can tell a full page from the last page without guessing from
/// `len < limit`. Goes to stderr so `--json` stdout stays byte-identical.
///
/// `n` is the count of results in the current page, so agents see exactly how
/// many they received before the "more results exist" hint.
#[cfg(test)]
pub(super) fn bounded_page_notice(n: usize, offset: usize, limit: usize) -> String {
    format!(
        "skim search: showing {n} result(s) (offset {offset}, limit {limit}); \
         more results exist. \
         Use --offset {} to page forward or increase --limit.",
        offset.saturating_add(limit)
    )
}

