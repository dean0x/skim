/// AD-414-7: lexical open failures become actionable — name the artifact path
/// and include the `--rebuild` hint.
///
/// Built with `anyhow::anyhow!` (NO `.context`), so the io source is not printed
/// twice when the caller formats with `{e:#}`.
///
/// Used by `gather_stats` (mod.rs), which serves both `--stats` and
/// `--stats --json` from one snapshot.  It runs AFTER the
/// `auto_refresh_if_stale` self-heal, so an error here means the index could
/// not be opened even after a rebuild attempt — exactly the state a stuck user
/// is in, and the one AC-13/AC-14 require to name the artifact and the
/// `--rebuild` remedy.
///
/// # Errors
///
/// Returns `Err` with the artifact path and rebuild guidance when the index
/// cannot be opened.
pub(super) fn open_lexical_reader(cache_dir: &Path) -> anyhow::Result<NgramIndexReader> {
    NgramIndexReader::open(cache_dir).map_err(|e| {
        anyhow::anyhow!(
            "failed to open lexical index at {}: {e}\n\
             Run `skim search --rebuild` to rebuild from scratch.",
            cache_dir.display()
        )
    })
}

