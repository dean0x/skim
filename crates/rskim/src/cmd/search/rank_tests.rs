fn input(path: &Path, prior: FilePrior, lines: u32, best: Role) -> LabelledInput<'_> {
    LabelledInput {
        path,
        prior,
        lines,
        best,
    }
}

fn order(ranked: &[Ranked]) -> Vec<usize> {
    ranked.iter().map(|r| r.index).collect()
}

#[test]
fn the_labelled_view_ranks_by_tier_then_prior_then_lines_then_path() {
    let p = |s: &str| PathBuf::from(s);
    let (a, b, c, d, e, f) = (p("a"), p("b"), p("c"), p("d"), p("e"), p("f"));
    let inputs = [
        input(&a, FilePrior::Source, 1, Role::Comment),
        input(&b, FilePrior::Test, 9, Role::Call),
        input(&c, FilePrior::Source, 2, Role::Call),
        input(&d, FilePrior::Source, 2, Role::Def),
        input(&e, FilePrior::Source, 7, Role::Call),
        input(&f, FilePrior::Source, 2, Role::Call),
    ];

    let ranked = rank_labelled(&inputs);

    // def first; then calls: source before test, more lines first, path last.
    assert_eq!(order(&ranked), [3, 4, 2, 5, 1, 0]);
}

#[test]
fn the_labelled_score_never_increases_down_the_list() {
    let paths: Vec<PathBuf> = (0..60).map(|i| PathBuf::from(format!("f{i:02}"))).collect();
    let roles = Role::ALL;
    let priors = [
        FilePrior::Source,
        FilePrior::Test,
        FilePrior::Docs,
        FilePrior::Changelog,
        FilePrior::Generated,
    ];
    let inputs: Vec<_> = paths
        .iter()
        .enumerate()
        .map(|(i, path)| {
            input(
                path,
                priors[i % priors.len()],
                [1, 2, 9, 10_000, 40_000][i % 5],
                roles[(i / 3) % roles.len()],
            )
        })
        .collect();

    let ranked = rank_labelled(&inputs);

    let scores: Vec<f64> = ranked.iter().map(|r| r.score).collect();
    assert!(never_increases(&scores), "{scores:?}");
    assert_eq!(ranked.len(), inputs.len());
}

#[test]
fn the_labelled_score_follows_the_documented_formula() {
    let path = PathBuf::from("a");
    let ranked = rank_labelled(&[input(&path, FilePrior::Test, 3, Role::Call)]);
    let expected = 100.0 * 8.0 + 10.0 * 3.0 + 9.99 * 3.0 / 4.2;
    assert!(
        (ranked[0].score - expected).abs() < 1e-9,
        "{}",
        ranked[0].score
    );
}

#[test]
fn the_lines_part_of_the_labelled_score_stops_at_the_cap() {
    let (a, b) = (PathBuf::from("a"), PathBuf::from("b"));
    let ranked = rank_labelled(&[
        input(&a, FilePrior::Source, 9_999, Role::Ref),
        input(&b, FilePrior::Source, 500_000, Role::Ref),
    ]);
    // More lines still rank first, with an equal score.
    assert_eq!(order(&ranked), [1, 0]);
    assert!((ranked[0].score - ranked[1].score).abs() < 1e-12);
}

