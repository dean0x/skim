//! Tests for the file prior and the rank order of both views.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::cmp::Ordering;
use std::path::{Path, PathBuf};

use super::*;

fn prior(path: &str) -> FilePrior {
    file_prior(Path::new(path), "fn main() {}\n")
}

fn never_increases(scores: &[f64]) -> bool {
    scores
        .windows(2)
        .all(|w| w[0].total_cmp(&w[1]) != Ordering::Less)
}

