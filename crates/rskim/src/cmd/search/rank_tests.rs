#[test]
fn source_files_are_the_default_prior() {
    for path in [
        "src/main.rs",
        "lib/util.py",
        "Makefile",
        "a/b/c.go",
        "script",
    ] {
        assert_eq!(prior(path), FilePrior::Source, "{path}");
    }
}

