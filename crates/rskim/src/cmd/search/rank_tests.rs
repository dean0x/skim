#[test]
fn a_lock_file_or_a_generated_header_has_the_generated_prior() {
    for path in [
        "Cargo.lock",
        "package-lock.json",
        "web/yarn.lock",
        "pnpm-lock.yaml",
        "poetry.lock",
        "go.sum",
    ] {
        assert_eq!(prior(path), FilePrior::Generated, "{path}");
    }
    for header in [
        "// @generated by tool\n",
        "# Auto-Generated file\n",
        "/* AUTOGENERATED */\n",
        "// DO NOT EDIT\n",
        "// do not edit\n",
    ] {
        let content = format!("{header}fn a() {{}}\n");
        assert_eq!(
            file_prior(Path::new("src/a.rs"), &content),
            FilePrior::Generated
        );
    }
}

#[test]
fn a_generated_marker_counts_only_in_the_first_five_lines() {
    let body = "fn a() {}\n".repeat(4);
    let inside = format!("{body}// @generated\n");
    let outside = format!("{body}fn b() {{}}\n// @generated\n");
    assert_eq!(file_prior(Path::new("a.rs"), &inside), FilePrior::Generated);
    assert_eq!(file_prior(Path::new("a.rs"), &outside), FilePrior::Source);
}

#[test]
fn a_generated_marker_past_the_probe_bytes_is_not_seen() {
    let content = format!(
        "{}\n// @generated\n",
        "x".repeat(GENERATED_PROBE_BYTES + 10)
    );
    assert_eq!(file_prior(Path::new("a.rs"), &content), FilePrior::Source);
}

#[test]
fn the_first_rule_that_fits_wins() {
    // Generated before changelog, changelog before docs, docs before test.
    assert_eq!(prior("tests/CHANGELOG.md"), FilePrior::Changelog);
    assert_eq!(prior("tests/notes.md"), FilePrior::Docs);
    assert_eq!(prior("docs/tests/a.rs"), FilePrior::Docs);
    assert_eq!(
        file_prior(Path::new("docs/CHANGELOG.md"), "// @generated\n"),
        FilePrior::Generated
    );
}

