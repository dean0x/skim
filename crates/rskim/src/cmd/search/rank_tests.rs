fn word_input<'a>(path: &'a Path, prior: FilePrior, counts: &'a [u32]) -> WordInput<'a> {
    WordInput {
        path,
        prior,
        counts,
    }
}

#[test]
fn the_word_view_ranks_by_words_then_prior_then_log_counts_then_path() {
    let p = |s: &str| PathBuf::from(s);
    let (a, b, c, d, e) = (p("a"), p("b"), p("c"), p("d"), p("e"));
    let (ca, cb, cc, cd, ce) = ([1, 1, 1], [9, 1, 1], [2, 0, 1], [30, 0, 0], [2, 0, 1]);
    let inputs = [
        word_input(&a, FilePrior::Test, &ca),
        word_input(&b, FilePrior::Source, &cb),
        word_input(&c, FilePrior::Source, &cc),
        word_input(&d, FilePrior::Source, &cd),
        word_input(&e, FilePrior::Source, &ce),
    ];

    let ranked = rank_words(&inputs);

    // b holds all words with source prior and the highest counts; a holds all
    // words but is a test; c and e tie and sort by path; d holds one word.
    assert_eq!(order(&ranked), [1, 0, 2, 4, 3]);
}

#[test]
fn a_few_matching_lines_in_many_words_beat_many_lines_of_one_word() {
    let (a, b) = (PathBuf::from("a"), PathBuf::from("b"));
    let (ca, cb) = ([1u32, 1, 1], [5_000u32, 0, 0]);
    let ranked = rank_words(&[
        word_input(&b, FilePrior::Source, &cb),
        word_input(&a, FilePrior::Source, &ca),
    ]);
    assert_eq!(order(&ranked), [1, 0]);
}

#[test]
fn the_word_score_never_increases_down_the_list_and_follows_its_formula() {
    let paths: Vec<PathBuf> = (0..40).map(|i| PathBuf::from(format!("f{i:02}"))).collect();
    let counts: Vec<[u32; 3]> = (0..40u32)
        .map(|i| [i % 4, (i / 4) % 3, 1000 * (i % 2)])
        .collect();
    let priors = [FilePrior::Source, FilePrior::Test, FilePrior::Docs];
    let inputs: Vec<_> = paths
        .iter()
        .zip(&counts)
        .enumerate()
        .map(|(i, (path, c))| word_input(path, priors[i % 3], c))
        .collect();

    let ranked = rank_words(&inputs);

    let scores: Vec<f64> = ranked.iter().map(|r| r.score).collect();
    assert!(never_increases(&scores), "{scores:?}");

    let path = PathBuf::from("x");
    let c = [3u32, 0, 1];
    let one = rank_words(&[word_input(&path, FilePrior::Docs, &c)]);
    let sum = 3f64.ln_1p() + 1f64.ln_1p();
    assert!((one[0].score - (2000.0 + 100.0 * 2.0 + sum)).abs() < 1e-9);
}

#[test]
fn files_holding_all_the_words_are_counted() {
    let paths: Vec<PathBuf> = ["a", "b", "c"].iter().map(PathBuf::from).collect();
    let counts = [[1u32, 2], [0, 4], [3, 3]];
    let inputs: Vec<_> = paths
        .iter()
        .zip(&counts)
        .map(|(p, c)| word_input(p, FilePrior::Source, c))
        .collect();
    assert_eq!(files_with_all_words(&inputs, 2), 2);
    assert_eq!(inputs[1].words_matched(), 1);
}

