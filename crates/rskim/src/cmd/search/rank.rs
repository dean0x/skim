//! Rank order of the files of a result, and the file prior.
//!
//! Two views rank files:
//!
//! - The **labelled view** (one pattern): key (best-role tier ascending, prior
//!   ascending, matched lines descending, path ascending).
//! - The **word view** (several plain words): key (words matched descending,
//!   prior ascending, sum of `ln(1 + count)` over the words descending, path
//!   ascending).
//!
//! One function per view computes the key and the score together, so the score
//! never increases down the ranked list.

use std::cmp::Reverse;
use std::path::{Component, Path};

use memchr::memmem;

use super::roles::Role;

/// Lines at the top of a file searched for a generated-file marker.
pub(super) const GENERATED_PROBE_LINES: usize = 5;

/// Bytes at the top of a file searched for a generated-file marker. It bounds
/// the work for a file whose first lines are very long.
const GENERATED_PROBE_BYTES: usize = 8192;

/// Fewer files than this holding all the words of a word query switches the
/// word view to its fallback.
pub(super) const FALLBACK_MIN_FILES: usize = 3;

/// Files listed by the word view when no limit is given.
pub(super) const WORD_VIEW_DEFAULT_LIMIT: usize = 10;

/// Lines listed per file by the word view.
pub(super) const WORD_VIEW_BEST_LINES: usize = 2;

/// Most words in a word query.
pub(super) const MAX_WORDS: usize = 16;

/// Matched lines above this count do not raise the score of a file.
const SCORE_LINES_CAP: u32 = 9999;

/// The word-count part of a word-view score stops at this value.
const WORD_SCORE_CAP: f64 = 99.0;

/// Markers of a generated file, lowercase, searched in the probe.
const GENERATED_MARKERS: [&str; 4] = [
    "@generated",
    "auto-generated",
    "autogenerated",
    "do not edit",
];

/// File names that are generated by a package manager.
const GENERATED_NAMES: [&str; 6] = [
    "Cargo.lock",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "go.sum",
];

const CHANGELOG_PREFIXES: [&str; 4] = ["changelog", "changes", "history", "news"];

const DOC_FOLDERS: [&str; 2] = ["docs", "doc"];

const DOC_EXTENSIONS: [&str; 6] = ["md", "mdx", "mds", "rst", "txt", "adoc"];

const TEST_FOLDERS: [&str; 7] = [
    "test",
    "tests",
    "__tests__",
    "spec",
    "e2e",
    "fixtures",
    "testdata",
];

/// How much a file is the place to look first. A lower value ranks first.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(super) enum FilePrior {
    Source,
    Test,
    Docs,
    Changelog,
    Generated,
}

impl FilePrior {
    /// The name in the output.
    pub(super) fn key(self) -> &'static str {
        match self {
            FilePrior::Source => "source",
            FilePrior::Test => "test",
            FilePrior::Docs => "docs",
            FilePrior::Changelog => "changelog",
            FilePrior::Generated => "generated",
        }
    }

    fn level(self) -> u32 {
        self as u32
    }
}

/// The prior of the file at `rel`, whose text is `content`. The first rule
/// that fits wins: generated, changelog, docs, test, source.
pub(super) fn file_prior(rel: &Path, content: &str) -> FilePrior {
    let name = rel
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    if GENERATED_NAMES.contains(&name.as_str()) || has_generated_marker(content) {
        return FilePrior::Generated;
    }
    let lower = name.to_ascii_lowercase();
    if CHANGELOG_PREFIXES.iter().any(|p| lower.starts_with(p)) {
        return FilePrior::Changelog;
    }
    let components: Vec<String> = rel
        .components()
        .filter_map(|c| match c {
            Component::Normal(part) => Some(part.to_string_lossy().into_owned()),
            _ => None,
        })
        .collect();
    let extension = rel
        .extension()
        .map(|e| e.to_string_lossy().into_owned())
        .unwrap_or_default();
    if components.iter().any(|c| DOC_FOLDERS.contains(&c.as_str()))
        || DOC_EXTENSIONS.contains(&extension.as_str())
    {
        return FilePrior::Docs;
    }
    if components
        .iter()
        .any(|c| TEST_FOLDERS.contains(&c.as_str()))
        || is_test_name(&name)
    {
        return FilePrior::Test;
    }
    FilePrior::Source
}

fn is_test_name(name: &str) -> bool {
    name.ends_with("_test.go")
        || name.ends_with("_test.py")
        || (name.starts_with("test_") && name.ends_with(".py"))
        || name.ends_with("_tests.rs")
        || has_dotted_infix(name, "test")
        || has_dotted_infix(name, "spec")
}

/// Whether `name` is `*.<infix>.*`: the infix is a whole dot-separated part
/// with something before and after it.
fn has_dotted_infix(name: &str, infix: &str) -> bool {
    let parts: Vec<&str> = name.split('.').collect();
    parts.len() >= 3 && parts[1..parts.len() - 1].contains(&infix)
}

fn has_generated_marker(content: &str) -> bool {
    let bytes = content.as_bytes();
    let probe = bytes[..bytes.len().min(GENERATED_PROBE_BYTES)].to_ascii_lowercase();
    probe
        .split(|&b| b == b'\n')
        .take(GENERATED_PROBE_LINES)
        .any(|line| {
            GENERATED_MARKERS
                .iter()
                .any(|marker| memmem::find(line, marker.as_bytes()).is_some())
        })
}

// ============================================================================
// Labelled view
// ============================================================================

/// What the labelled view ranks one file by.
#[derive(Debug, Clone, Copy)]
pub(super) struct LabelledInput<'a> {
    pub(super) path: &'a Path,
    pub(super) prior: FilePrior,
    /// Matching lines in the file.
    pub(super) lines: u32,
    /// The best role among those lines.
    pub(super) best: Role,
}

/// One file in rank order: its index in the input, and its score.
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct Ranked {
    pub(super) index: usize,
    pub(super) score: f64,
}

/// The key and the score of one file of the labelled view, from one place.
/// `score = 100 * (9 - tier) + 10 * (4 - prior) + 9.99 * c / (c + 1.2)` with
/// `c = min(lines, 9999)`.
fn labelled_rank(input: &LabelledInput<'_>) -> ((u32, u32, Reverse<u32>), f64) {
    let tier = input.best.tier();
    let prior = input.prior.level();
    let capped = f64::from(input.lines.min(SCORE_LINES_CAP));
    let score =
        100.0 * f64::from(9 - tier) + 10.0 * f64::from(4 - prior) + 9.99 * capped / (capped + 1.2);
    ((tier, prior, Reverse(input.lines)), score)
}

/// Rank files of the labelled view, best first.
pub(super) fn rank_labelled(inputs: &[LabelledInput<'_>]) -> Vec<Ranked> {
    let mut keyed: Vec<_> = inputs
        .iter()
        .enumerate()
        .map(|(index, input)| {
            let (key, score) = labelled_rank(input);
            (key, input.path, Ranked { index, score })
        })
        .collect();
    keyed.sort_by(|a, b| a.0.cmp(&b.0).then_with(|| a.1.cmp(b.1)));
    keyed.into_iter().map(|(_, _, ranked)| ranked).collect()
}

